package usecases

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"github.com/datosbolivia/open-knowledge-format/src/domain"
	"gopkg.in/yaml.v3"
)

type IndexReport struct {
	BundleDir       string   `json:"bundle_dir"`
	IndexFilePath   string   `json:"index_file_path"`
	ConceptsIndexed int      `json:"concepts_indexed"`
	TypesFound      []string `json:"types_found"`
}

type ConceptSummary struct {
	RelativePath string
	Type         string
	Title        string
	Description  string
	Status       string
	Tags         []string
}

// GenerateIndex automatically indexes all concept documents in a bundle to support progressive disclosure (OKF §8).
func GenerateIndex(bundleDir string) (*IndexReport, error) {
	info, err := os.Stat(bundleDir)
	if err != nil {
		return nil, fmt.Errorf("bundle directory error: %w", err)
	}
	if !info.IsDir() {
		return nil, fmt.Errorf("target '%s' is not a directory", bundleDir)
	}

	var concepts []ConceptSummary
	typesMap := make(map[string]bool)

	err = filepath.Walk(bundleDir, func(path string, fi os.FileInfo, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if fi.IsDir() {
			return nil
		}

		baseName := fi.Name()
		if !strings.HasSuffix(baseName, ".md") {
			return nil
		}

		// Skip index.md, log.md, and README.md
		lowerName := strings.ToLower(baseName)
		if lowerName == "index.md" || lowerName == "log.md" || lowerName == "readme.md" {
			return nil
		}

		contentBytes, err := os.ReadFile(path)
		if err != nil {
			return nil
		}
		content := string(contentBytes)

		relPath, err := filepath.Rel(bundleDir, path)
		if err != nil {
			relPath = path
		}

		lines := strings.Split(content, "\n")
		if len(lines) < 3 || strings.TrimSpace(lines[0]) != "---" {
			return nil
		}

		endIdx := -1
		for i := 1; i < len(lines); i++ {
			if strings.TrimSpace(lines[i]) == "---" {
				endIdx = i
				break
			}
		}
		if endIdx == -1 {
			return nil
		}

		var fm domain.ConceptFrontmatter
		if err := yaml.Unmarshal([]byte(strings.Join(lines[1:endIdx], "\n")), &fm); err != nil {
			return nil
		}

		cType := strings.TrimSpace(fm.Type)
		if cType == "" {
			cType = "concept"
		}
		typesMap[cType] = true

		title := strings.TrimSpace(fm.Title)
		if title == "" {
			title = strings.TrimSuffix(baseName, ".md")
		}

		status := strings.TrimSpace(fm.Status)
		if status == "" {
			status = "active"
		}

		concepts = append(concepts, ConceptSummary{
			RelativePath: relPath,
			Type:         cType,
			Title:        title,
			Description:  strings.TrimSpace(fm.Description),
			Status:       status,
			Tags:         fm.Tags,
		})

		return nil
	})

	if err != nil {
		return nil, fmt.Errorf("failed scanning bundle: %w", err)
	}

	// Sort concepts by type, then title
	sort.Slice(concepts, func(i, j int) bool {
		if concepts[i].Type == concepts[j].Type {
			return concepts[i].Title < concepts[j].Title
		}
		return concepts[i].Type < concepts[j].Type
	})

	var typesFound []string
	for t := range typesMap {
		typesFound = append(typesFound, t)
	}
	sort.Strings(typesFound)

	nowISO := time.Now().UTC().Format(time.RFC3339)
	bundleName := filepath.Base(bundleDir)

	var sb strings.Builder
	sb.WriteString("---\n")
	sb.WriteString("type: index\n")
	sb.WriteString(fmt.Sprintf("title: \"%s Index\"\n", bundleName))
	sb.WriteString(fmt.Sprintf("description: \"Automatically generated index for progressive disclosure in %s\"\n", bundleName))
	sb.WriteString("generated:\n")
	sb.WriteString("  by: \"okf CLI\"\n")
	sb.WriteString(fmt.Sprintf("  at: \"%s\"\n", nowISO))
	sb.WriteString("---\n\n")

	sb.WriteString(fmt.Sprintf("# %s Index\n\n", bundleName))
	sb.WriteString("This index is maintained automatically per **Open Knowledge Format (OKF v0.2) §8** to enable token-efficient, progressive disclosure across agent and human workflows.\n\n")

	sb.WriteString("## Concepts by Category\n\n")
	sb.WriteString("| Title | Type | Description | Status | Path |\n")
	sb.WriteString("| :--- | :--- | :--- | :--- | :--- |\n")

	for _, c := range concepts {
		desc := c.Description
		if desc == "" {
			desc = "-"
		}
		// Escape pipe characters in table
		desc = strings.ReplaceAll(desc, "|", "\\|")
		titleClean := strings.ReplaceAll(c.Title, "|", "\\|")

		sb.WriteString(fmt.Sprintf("| [%s](%s) | `%s` | %s | `%s` | `%s` |\n",
			titleClean, c.RelativePath, c.Type, desc, c.Status, c.RelativePath))
	}

	sb.WriteString("\n---\n*Generated by okf index tool.*\n")

	indexPath := filepath.Join(bundleDir, "index.md")
	if err := os.WriteFile(indexPath, []byte(sb.String()), 0644); err != nil {
		return nil, fmt.Errorf("failed to write index.md: %w", err)
	}

	return &IndexReport{
		BundleDir:       bundleDir,
		IndexFilePath:   indexPath,
		ConceptsIndexed: len(concepts),
		TypesFound:      typesFound,
	}, nil
}
